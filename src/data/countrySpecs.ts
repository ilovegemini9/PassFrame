export function filterSpecsByRegion(specs: CountryPhotoSpec[], region: Region | 'All'): CountryPhotoSpec[] {
  if (region === 'All') return specs;
  return specs.filter((spec) => spec.region === region);
}

export function searchCountrySpecs(specs: CountryPhotoSpec[], query: string): CountryPhotoSpec[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return specs;
  return specs.filter(
    (spec) =>
      spec.country.toLowerCase().includes(normalized) ||
      spec.document.toLowerCase().includes(normalized) ||
      spec.keywords.some((kw) => kw.toLowerCase().includes(normalized))
  );
}

export function formatPhysicalDimensions(spec: CountryPhotoSpec): string {
  if (spec.unit === 'in' && spec.widthIn && spec.heightIn) {
    return `${spec.widthIn} × ${spec.heightIn} in`;
  }
  if (spec.unit === 'px') {
    return `${spec.widthPx} × ${spec.heightPx} px`;
  }
  return `${spec.widthMm} × ${spec.heightMm} mm`;
}

export function getSpecBySlug(slug: string): CountryPhotoSpec | undefined {
  return COUNTRY_SPECS.find((spec) => spec.slug === slug);
}

export function getSpecById(id: string): CountryPhotoSpec | undefined {
  return COUNTRY_SPECS.find((spec) => spec.id === id);
}

export function getSpecUrlPath(spec: CountryPhotoSpec): string {
  return `/photo/${spec.slug}`;
}

